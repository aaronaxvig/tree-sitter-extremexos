"""Generate Tree-sitter command families from ExtremeXOS CLI XML."""

import argparse
from collections import defaultdict
from functools import cache
import hashlib
from itertools import chain
import json
from pathlib import Path
import re
from xml.etree import ElementTree as ET

from .clidef_to_grammar import DEAD_END, SYNTAX_TAGS, command_graph, identifier, static_choices
from .import_topics import GENERATED as KEYWORDS_MARKER
from .import_topics import KEYWORD, ROOT, keyword_files, literal_topics


MARKER = "// Generated by tools.import_grammar.\n"


def read_module(path):
    data = path.read_text(encoding="utf-8-sig")
    if re.search(r"<!\s*(?:DOCTYPE|ENTITY)\b", data, re.IGNORECASE):
        raise ValueError("DTD and entity declarations are unsupported")
    root = ET.fromstring(data)
    tree = root.find('./cmd_tree[@name="extreme"]')
    if tree is None:
        raise ValueError("No ExtremeXOS command tree found")
    graph = command_graph(tree) if any(child.tag in SYNTAX_TAGS for child in tree) else DEAD_END
    return tree, graph, static_choices(root)


def load_families(paths, verbs):
    families = defaultdict(list)
    keywords = defaultdict(set)
    errors = []
    for path in sorted(paths):
        try:
            tree, graph, static = read_module(path)
        except (OSError, ValueError, ET.ParseError, RecursionError) as error:
            errors.append(f"{path.name}: {error}")
            continue
        for verb, topic in literal_topics(tree, verbs):
            keywords[verb].add(topic)
        for verb, branches in graph.transitions:
            if verb.operand_type is not None or verb.name not in verbs:
                continue
            for topic, state in branches.transitions:
                if topic.operand_type is None and KEYWORD.fullmatch(topic.name):
                    families[verb.name, topic.name].append((state, path.name, static))
    return families, keywords, errors


def render_family(verb, topic, sources):
    """Emit one rule per shared continuation without enumerating command paths."""
    stem = f"{verb}_{topic.replace('-', '_')}"
    static = {path: choices for _, path, choices in sources}
    rules = {}

    @cache
    def state_rule(targets):
        edges = defaultdict(list)
        for state, path in targets:
            for token, following in state.transitions:
                literals = static[path].get(token.operand_type, ())
                if token.operand_type is None:
                    literals = (token.name,)
                if literals:
                    for literal in literals:
                        field = identifier(token.name) if token.operand_type is not None else None
                        edges[literal].append((field, following, path))
                else:
                    edges[None].append((identifier(token.name), following, path))
        if not edges:
            return "_arguments"
        branches = []
        for literal, matching in sorted(edges.items(), key=lambda entry: (entry[0] is None, entry[0] or "")):
            following = tuple(dict.fromkeys((state, path) for _, state, path in matching))
            continuation = state_rule(following)
            token = "$.word_or_string" if literal is None else json.dumps(literal)
            fields = {name for name, _, _ in matching}
            if None not in fields:
                field = next(iter(fields)) if len(fields) == 1 else "argument"
                token = f"field({json.dumps(field)}, {token})"
            branch = f"seq({token}, optional($.{continuation}))"
            if literal is not None:
                branch = f"prec(1, {branch})"
            branches.append(branch)
        if None not in edges:
            branches.append("$._arguments")
        digest = hashlib.sha256("\n".join(branches).encode()).hexdigest()[:16]
        name = f"_{stem}_{digest}"
        rules[name] = branches
        return name

    continuation = state_rule(tuple((state, path) for state, path, _ in sources))
    lines = [
        MARKER.rstrip(),
        "const rules = () => ({",
        f"  {stem}: $ => seq({json.dumps(topic)}, optional($.{continuation})),",
    ]
    for name, branches in sorted(rules.items()):
        if len(branches) == 1:
            lines.append(f"  {name}: $ => {branches[0]},")
        else:
            lines.append(f"  {name}: $ => choice(")
            lines.extend(f"    {branch}," for branch in branches)
            lines.append("  ),")
    lines.extend(["});", "", "module.exports = {rules};", ""])
    return "\n".join(lines)


def output_files(families):
    by_verb = defaultdict(list)
    for (verb, topic), sources in sorted(families.items()):
        by_verb[verb].append(topic)
        yield Path(verb, f"{topic}.js"), render_family(verb, topic, sources)
    index = [MARKER.rstrip(), "module.exports = {"]
    for verb, topics in sorted(by_verb.items()):
        index.append(f"  {json.dumps(verb)}: {{")
        for topic in topics:
            index.append(f"    {json.dumps(topic)}: require({json.dumps(f'./{verb}/{topic}')}),")
        index.append("  },")
    index.extend(["};", ""])
    yield Path("generated.js"), "\n".join(index)


def write_files(output, families, keywords):
    files = {}
    markers = (MARKER, KEYWORDS_MARKER)
    for relative, content in chain(output_files(families), keyword_files(keywords)):
        if relative in files:
            raise ValueError(f"Generated paths collide at {relative}")
        files[relative] = content
    for relative in files:
        path = output / relative
        if path.exists() and not path.read_text(encoding="utf-8").startswith(markers):
            raise ValueError(f"Existing file is outside the generated set: {path}")
    for relative, content in files.items():
        path = output / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    for path in output.glob("*/*.js"):
        if path.relative_to(output) not in files and path.read_text(encoding="utf-8").startswith(markers):
            path.unlink()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path, help="Extracted config/clidef directory")
    parser.add_argument("--output", type=Path, default=ROOT / "grammar")
    parser.add_argument("--all", action="store_true", help="Generate detailed rules for every public family")
    options = parser.parse_args()
    paths = list(options.directory.glob("*.xml"))
    if not paths:
        parser.exit(1, f"No CLI XML files found in {options.directory}\n")
    try:
        config = json.loads((ROOT / "grammar/import.json").read_text())
        families, keywords, errors = load_families(paths, set(config["verbs"]))
        if errors:
            parser.exit(1, "\n".join(errors) + "\n")
        detailed = {(verb, topic) for verb, topics in config["detailed"].items() for topic in topics}
        selected = {
            (verb, topic): sources for (verb, topic), sources in families.items()
            if topic in keywords[verb] and (options.all or (verb, topic) in detailed)
        }
        write_files(options.output, selected, keywords)
    except (OSError, ValueError, RecursionError) as error:
        parser.exit(1, f"{error}\n")
    print(f"Generated {len(selected)} detailed command families from {len(paths)} XML files.")
    if not options.all:
        for verb, topic in sorted(detailed - selected.keys()):
            print(f"No detailed definition for {verb} {topic} in supplied XML.")


if __name__ == "__main__":
    main()
