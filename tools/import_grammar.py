"""Generate Tree-sitter command families from ExtremeXOS CLI XML."""

import argparse
from collections import defaultdict
from functools import cache
import hashlib
from itertools import chain
import json
from pathlib import Path
import re
from xml.etree import ElementTree as ET

from .clidef_to_grammar import DEAD_END, SYNTAX_TAGS, State, command_graph, identifier, static_choices
from .import_topics import GENERATED as KEYWORDS_MARKER
from .import_topics import KEYWORD, OMITTED_FLAGS, ROOT, keyword_files


MARKER = "// Generated by tools.import_grammar.\n"


def read_module(path):
    data = path.read_text(encoding="utf-8-sig")
    if re.search(r"<!\s*(?:DOCTYPE|ENTITY)\b", data, re.IGNORECASE):
        raise ValueError("DTD and entity declarations are unsupported")
    root = ET.fromstring(data)
    tree = root.find('./cmd_tree[@name="extreme"]')
    if tree is None:
        raise ValueError("No ExtremeXOS command tree found")
    graph = command_graph(tree) if any(child.tag in SYNTAX_TAGS for child in tree) else DEAD_END
    public = graph
    if graph is not DEAD_END and any(flag.text in OMITTED_FLAGS for flag in tree.iter("flags")):
        public = command_graph(tree, OMITTED_FLAGS)
    return graph, public, static_choices(root)


def load_families(paths, excluded_verbs=()):
    families = defaultdict(list)
    keywords = defaultdict(set)
    observed = defaultdict(set)
    public_prefixes = set()
    errors = []
    for path in sorted(paths):
        try:
            graph, public, static = read_module(path)
        except (OSError, ValueError, ET.ParseError, RecursionError) as error:
            errors.append(f"{path.name}: {error}")
            continue
        for verb, branches in graph.transitions:
            if branches.can_end:
                observed[verb, None].add(path.name)
            for topic, _ in branches.transitions:
                observed[verb, topic].add(path.name)
        for verb, branches in public.transitions:
            if branches.can_end:
                public_prefixes.add((verb, None))
            public_prefixes.update((verb, token) for token, _ in branches.transitions)
            if verb.operand_type is not None or verb.name in excluded_verbs or not KEYWORD.fullmatch(verb.name):
                continue
            topics = keywords[verb.name]
            operands = []
            for topic, state in branches.transitions:
                if topic.operand_type is not None:
                    operands.append((topic, state))
                elif re.fullmatch(r"-{0,2}[a-zA-Z0-9][a-zA-Z0-9_-]*", topic.name):
                    topics.add(topic.name)
                    families[verb.name, topic.name].append((state, path.name, static))
            if operands:
                families[verb.name, "_operand"].append((State(False, tuple(operands)), path.name, static))
    return families, keywords, errors, observed, public_prefixes


def coverage_report(observed, verbs, keywords, selected, supplemental, excluded_verbs, public_prefixes):
    """Classify XML command prefixes against the rules emitted for this import."""
    def spelling(token):
        return token.name if token.operand_type is None else f"<{token.name}>"

    rows = []
    for (verb, topic), sources in observed.items():
        command = spelling(verb)
        if topic is not None:
            command += " " + spelling(topic)
        if verb.operand_type is not None:
            status, reason = "skipped", "operand in verb position"
        elif verb.name in excluded_verbs:
            status, reason = "excluded", "excluded verb"
        elif (verb, topic) not in public_prefixes:
            status, reason = "excluded", "XML visibility flag"
        elif verb.name not in verbs:
            status, reason = "skipped", "unregistered verb"
        elif topic is None:
            status, reason = "covered", "verb without arguments"
        elif topic.operand_type is not None:
            sources_for_operand = selected.get((verb.name, "_operand"), ())
            if any(token == topic for state, _, _ in sources_for_operand for token, _ in state.transitions):
                status, reason = "detailed", "generated operand rule"
            else:
                status, reason = "generic", "operand after verb"
        elif (verb.name, topic.name) in selected:
            status, reason = "detailed", "generated family"
        elif topic.name in keywords.get(verb.name, ()) or topic.name in supplemental.get(verb.name, ()):
            status, reason = "generic", "topic with generic arguments"
        else:
            status, reason = "skipped", "outside public topic list"
        rows.append(dict(command=command, status=status, reason=reason, sources=sorted(sources)))
    return sorted(rows, key=lambda row: (row["command"], row["reason"]))


def render_family(verb, topic, sources, emitted):
    """Emit one rule per distinct continuation, sharing them across families."""
    stem = f"{verb.replace('-', '_')}_{topic.replace('-', '_')}"
    static = {path: choices for _, path, choices in sources}
    rules = {}

    @cache
    def state_rule(targets):
        edges = defaultdict(list)
        for state, path in targets:
            for token, following in state.transitions:
                literals = static[path].get(token.operand_type, ())
                if token.operand_type is None:
                    literals = (token.name,)
                if literals:
                    for literal in literals:
                        field = identifier(token.name) if token.operand_type is not None else None
                        edges[literal].append((field, following, path))
                else:
                    edges[None].append((identifier(token.name), following, path))
        if not edges:
            return "_arguments"
        branches = []
        for literal, matching in sorted(edges.items(), key=lambda entry: (entry[0] is None, entry[0] or "")):
            following = tuple(dict.fromkeys((state, path) for _, state, path in matching))
            continuation = state_rule(following)
            token = "$.word_or_string" if literal is None else json.dumps(literal)
            fields = {name for name, _, _ in matching}
            if None not in fields:
                field = next(iter(fields)) if len(fields) == 1 else "argument"
                token = f"field({json.dumps(field)}, {token})"
            branch = f"seq({token}, optional($.{continuation}))"
            if literal is not None:
                branch = f"prec(1, {branch})"
            branches.append(branch)
        if None not in edges:
            branches.append("$._arguments")
        digest = hashlib.sha256("\n".join(branches).encode()).hexdigest()[:16]
        name = f"_continue_{digest}"
        if name not in emitted:
            rules[name] = branches
            emitted.add(name)
        return name

    continuation = state_rule(tuple((state, path) for state, path, _ in sources))
    entry = f"$.{continuation}"
    if topic != "_operand":
        entry = f"seq({json.dumps(topic)}, optional({entry}))"
    lines = [
        MARKER.rstrip(),
        "const rules = ({choice, field, optional, prec, seq} = globalThis) => ({",
        f"  {stem}: $ => {entry},",
    ]
    for name, branches in sorted(rules.items()):
        if len(branches) == 1:
            lines.append(f"  {name}: $ => {branches[0]},")
        else:
            lines.append(f"  {name}: $ => choice(")
            lines.extend(f"    {branch}," for branch in branches)
            lines.append("  ),")
    lines.extend(["});", "", "module.exports = {rules};", ""])
    return "\n".join(lines)


def output_files(families):
    by_verb = defaultdict(list)
    emitted = set()
    for verb, topic in sorted(families):
        sources = families[verb, topic]
        by_verb[verb].append(topic)
        yield Path(verb, f"{topic}.js"), render_family(verb, topic, sources, emitted)
    index = [MARKER.rstrip(), "module.exports = {"]
    for verb, topics in sorted(by_verb.items()):
        index.append(f"  {json.dumps(verb)}: {{")
        for topic in sorted(topics):
            index.append(f"    {json.dumps(topic)}: require({json.dumps(f'./{verb}/{topic}')}),")
        index.append("  },")
    index.extend(["};", ""])
    yield Path("generated.js"), "\n".join(index)


def write_files(output, families, keywords):
    files = {}
    markers = (MARKER, KEYWORDS_MARKER)
    for relative, content in chain(output_files(families), keyword_files(keywords)):
        if relative in files:
            raise ValueError(f"Generated paths collide at {relative}")
        files[relative] = content
    for relative in files:
        path = output / relative
        if path.exists() and not path.read_text(encoding="utf-8").startswith(markers):
            raise ValueError(f"Existing file is outside the generated set: {path}")
    for relative, content in files.items():
        path = output / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    for path in output.glob("*/*.js"):
        if path.relative_to(output) not in files and path.read_text(encoding="utf-8").startswith(markers):
            path.unlink()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path, help="Extracted config/clidef directory")
    parser.add_argument("--output", type=Path, default=ROOT / "grammar")
    parser.add_argument("--all", action="store_true", help="Import every public family (the default)")
    parser.add_argument("--coverage", type=Path, metavar="FILE", help="Write command prefix coverage and XML sources as JSON")
    options = parser.parse_args()
    paths = list(options.directory.glob("*.xml"))
    if not paths:
        parser.exit(1, f"No CLI XML files found in {options.directory}\n")
    try:
        config = json.loads((ROOT / "grammar/import.json").read_text())
        excluded = config["excluded_verbs"]
        families, keywords, errors, observed, public_prefixes = load_families(paths, excluded)
        verbs = set(keywords) | set(config["verbs"])
        if errors:
            parser.exit(1, "\n".join(errors) + "\n")
        rows = coverage_report(observed, verbs, keywords, families, config["supplemental"], excluded, public_prefixes)
        write_files(options.output, families, keywords)
        if options.coverage:
            options.coverage.write_text(json.dumps(rows, indent=2) + "\n", encoding="utf-8")
    except (OSError, ValueError, RecursionError) as error:
        parser.exit(1, f"{error}\n")
    print(f"Generated {len(families)} detailed command families from {len(paths)} XML files.")
    for status in ("detailed", "covered", "generic", "excluded", "skipped"):
        print(f"{sum(row['status'] == status for row in rows)} {status} XML command prefixes")
    unknown = sorted({verb.name for verb, _ in observed if verb.operand_type is None and verb.name not in verbs and verb.name not in excluded})
    if unknown:
        print("Unregistered XML verbs: " + ", ".join(unknown))
    if not options.coverage:
        print("Use --coverage FILE for command prefixes, reasons and source XML files.")


if __name__ == "__main__":
    main()
