"""Import literal first-level CLI topics into per-verb keyword lists."""

import argparse
from collections import defaultdict
import json
from pathlib import Path
import re
from xml.etree import ElementTree as ET

from .clidef_to_grammar import SYNTAX_TAGS, group_id, has_continuation


ROOT = Path(__file__).resolve().parents[1]
GENERATED = "// Generated by tools.import_topics.\n"
KEYWORD = re.compile(r"[a-zA-Z0-9][a-zA-Z0-9_-]*")
OMITTED_FLAGS = {"debug-only", "lawful-intercept", "prompting-only"}


def registered_verbs(grammar):
    rules = grammar["rules"]

    def leading(rule):
        kind = rule["type"]
        if kind == "STRING":
            yield rule["value"]
        elif kind == "SYMBOL":
            yield from leading(rules[rule["name"]])
        elif kind == "SEQ":
            yield from leading(rule["members"][0])
        elif kind == "CHOICE":
            for member in rule["members"]:
                yield from leading(member)
        elif kind.startswith("PREC"):
            yield from leading(rule["content"])

    return set(leading(rules["command"]))


def literal_topics(tree, verbs):
    """Read two literal tokens, including shared continuations between them."""
    closers = {group_id(node)[1]: node for node in tree.iter("close")}
    topics = set()
    visited = set()

    def walk(node, verb=None, groups=()):
        state = (node, verb, groups)
        if state in visited or any(flag.text in OMITTED_FLAGS for flag in node.findall("flags")):
            return
        visited.add(state)
        if node.tag == "arg":
            return
        if node.tag == "key":
            word = node.findtext("name", "")
            if verb is not None:
                if KEYWORD.fullmatch(word):
                    topics.add((verb, word))
                return
            if word not in verbs:
                return
            verb = word
        elif node.tag == "close":
            if not groups or node is not groups[-1]:
                return
            groups = groups[:-1]

        branches = [child for child in node if child.tag in SYNTAX_TAGS]
        if node.tag == "open":
            delimiter, marker = group_id(node)
            closer = closers.get(marker)
            boundary = closer if closer is not None else node
            if boundary in groups:
                return
            groups = (*groups, boundary)
            if closer is not None and delimiter == "{":
                walk(closer, verb, groups)
            branches = [child for child in branches if child is not closer]

        # A childless operand beside keywords is a shared prefix in the CLI
        # format. Those keywords follow that operand instead of replacing it.
        operands = [child for child in branches if child.tag == "arg"]
        if operands and len(branches) > 1:
            if len(operands) > 1 or not has_continuation(operands[0]):
                return

        for child in branches:
            walk(child, verb, groups)
        if node.tag != "open" and not branches and node.find("action") is None and groups and groups[-1].tag == "close":
            walk(groups[-1], verb, groups)

    walk(tree)
    return topics


def import_topics(directory, verbs):
    topics = defaultdict(set)
    files = sorted(directory.glob("*.xml"))
    if not files:
        raise ValueError(f"No CLI XML files found in {directory}")
    for path in files:
        data = path.read_text(encoding="utf-8-sig")
        if re.search(r"<!\s*(?:DOCTYPE|ENTITY)\b", data, re.IGNORECASE):
            raise ValueError(f"DTD and entity declarations are unsupported in {path}")
        tree = ET.fromstring(data).find('./cmd_tree[@name="extreme"]')
        if tree is None:
            raise ValueError(f"No ExtremeXOS command tree found in {path}")
        for verb, topic in literal_topics(tree, verbs):
            topics[verb].add(topic)
    return topics


def write_keywords(output, topics):
    index = [GENERATED.rstrip(), "module.exports = {"]
    for verb, words in sorted(topics.items()):
        folder = output / verb
        folder.mkdir(parents=True, exist_ok=True)
        listing = ",\n".join(f"  {json.dumps(word)}" for word in sorted(words))
        (folder / "keywords.js").write_text(GENERATED + f"module.exports = [\n{listing},\n];\n")
        index.append(f'  {json.dumps(verb)}: require("./{verb}/keywords"),')
    (output / "keywords.js").write_text("\n".join([*index, "};", ""]))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path, help="Extracted config/clidef directory")
    parser.add_argument("--output", type=Path, default=ROOT / "grammar", help="Grammar directory")
    options = parser.parse_args()
    try:
        grammar = json.loads((ROOT / "src/grammar.json").read_text())
        topics = import_topics(options.directory, registered_verbs(grammar))
        write_keywords(options.output, topics)
    except (OSError, ValueError, ET.ParseError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
